// image (for example "/logos/iit-bombay.png" placed in the public folder) or to null
// to show initials instead.
function org(name, type, domain, { logo = true } = {}) {
  return {
    name,
    type, // College | Company | Startup | Platform
    website: `https://${domain}`,
    logo: logo ? `https://www.google.com/s2/favicons?domain=${domain}&sz=128` : null,
  }
}

